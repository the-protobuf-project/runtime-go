// DefaultBasePath is where a combined server mounts when no base path is
// configured: the one path an agent connects to for every service.
const DefaultBasePath = "/mcp"

// Registration adds one service's tools, prompts, resources and resource
// templates to a server. It is a generated RegisterFooMCPHandler with its
// implementation and options bound:
//
//	func(s *mcp.Server) { yourpb.RegisterYourServiceMCPHandler(s, impl) }
type Registration func(s *mcp.Server)

// NewCombinedServer builds ONE MCP server carrying every registration, so an
// agent connects to a single endpoint for every service rather than to one
// endpoint per service.
//
// The server identifies itself by cfg.Name and cfg.Version and is built with
// cfg.ServerOptions, so the caller decides what a combined server is called and
// what its instructions say; no one service's identity speaks for the rest.
//
// The SDK lets a second AddTool with a name already taken replace the first
// without a word, which on a combined server would make one service's tool
// silently answer for another's. So every registration is inventoried on its
// own first, and two declaring the same tool name, prompt name, resource URI or
// resource template URI is an error naming each clash — the process fails at
// startup instead of serving the wrong handler. Generated tool names carry the
// service's name as a prefix, so services from different packages do not clash
// unless two of them share a service name.
func NewCombinedServer(cfg *MCPServerConfig, regs ...Registration) (*mcp.Server, error) {
	if err := checkCollisions(regs); err != nil {
		return nil, err
	}
	s := NewMCPServer(cfg)
	for _, reg := range regs {
		reg(s)
	}
	return s, nil
}

// CombineServices is [NewCombinedServer] for generated ServeFooMCP functions —
// the [ServiceFunc]s a program already hands to [ServiceGroup] or to the
// HybridServer — so services generated by any protoc-gen-mcp release combine
// without regenerating.
//
// Each function is run once against a config that asks [StartServer] to hand
// its registration back rather than serve it, and returns at once. That keeps
// everything the generated function wires around its registration: the unary
// interceptor (cfg.UnaryInterceptor) reaches every tool, and the completion
// handler it derives from its prompts' enum values is merged into the combined
// server's, each consulted in turn.
//
// The functions are collected in order, so the result is the same on every run.
// A function that returns without registering — anything other than a generated
// ServeFooMCP — is an error.
func CombineServices(ctx context.Context, cfg *MCPServerConfig, fns ...ServiceFunc) (*mcp.Server, error) {
	regs := make([]Registration, 0, len(fns))
	var completions []completionHandler
	for i, fn := range fns {
		collected := false
		c := *cfg
		// Fresh options per function: a generated ServeFooMCP writes its
		// completion handler into them, which must neither leak into the
		// caller's config nor overwrite a sibling's.
		c.ServerOptions = nil
		c.Mux = nil
		c.OnReady = nil
		c.collect = func(resolved *MCPServerConfig, register func(*mcp.Server)) {
			collected = true
			regs = append(regs, register)
			if resolved.ServerOptions != nil && resolved.ServerOptions.CompletionHandler != nil {
				completions = append(completions, resolved.ServerOptions.CompletionHandler)
			}
		}
		if err := fn(ctx, &c); err != nil {
			return nil, fmt.Errorf("mcp: combining service #%d: %w", i, err)
		}
		if !collected {
			return nil, fmt.Errorf("mcp: service #%d returned without registering; only a generated ServeFooMCP can be combined", i)
		}
	}

	combined := *cfg
	combined.collect = nil
	if len(completions) > 0 {
		opts := &mcp.ServerOptions{}
		if cfg.ServerOptions != nil {
			// Shallow copy: the caller's options are not ours to modify.
			copied := *cfg.ServerOptions
			opts = &copied
		}
		if opts.CompletionHandler != nil {
			completions = append([]completionHandler{opts.CompletionHandler}, completions...)
		}
		opts.CompletionHandler = chainCompletions(completions)
		combined.ServerOptions = opts
	}
	return NewCombinedServer(&combined, regs...)
}

// NewHTTPHandler serves s over cfg's HTTP transports at cfg.BasePath
// ([DefaultBasePath] when empty), with cfg.HeaderMappings applied — the handler
// a process mounts on a mux it already owns. A stdio transport in cfg is
// ignored, since it does not travel over HTTP, and a config naming no HTTP
// transport is served over streamable HTTP.
func NewHTTPHandler(s *mcp.Server, cfg *MCPServerConfig) (http.Handler, error) {
	resolved := *cfg
	if resolved.BasePath == "" {
		resolved.BasePath = DefaultBasePath
	}
	httpTransports, _, err := resolveTransports(&resolved)
	if err != nil {
		return nil, err
	}
	if len(httpTransports) == 0 {
		httpTransports = []Transport{TransportStreamableHTTP}
	}
	return buildHTTPMux(s, &resolved, httpTransports), nil
}

// completionHandler is the shape of [mcp.ServerOptions.CompletionHandler].
type completionHandler = func(context.Context, *mcp.CompleteRequest) (*mcp.CompleteResult, error)

// chainCompletions asks each handler in turn and answers with the first that
// offers any value. Each generated handler knows only its own prompts and
// answers an empty list for the rest, so on a combined server at most one of
// them has anything to say about a given prompt.
func chainCompletions(handlers []completionHandler) completionHandler {
	return func(ctx context.Context, req *mcp.CompleteRequest) (*mcp.CompleteResult, error) {
		var firstErr error
		for _, h := range handlers {
			res, err := h(ctx, req)
			if err != nil {
				if firstErr == nil {
					firstErr = err
				}
				continue
			}
			if res != nil && len(res.Completion.Values) > 0 {
				return res, nil
			}
		}
		if firstErr != nil {
			return nil, firstErr
		}
		return &mcp.CompleteResult{Completion: mcp.CompletionResultDetails{Values: []string{}}}, nil
	}
}

// checkCollisions inventories each registration on a server of its own and
// reports every name two of them declare.
func checkCollisions(regs []Registration) error {
	owner := map[string]int{}
	var errs []error
	for i, reg := range regs {
		names, err := inventory(reg)
		if err != nil {
			return fmt.Errorf("mcp: inventorying service #%d: %w", i, err)
		}
		for _, name := range names {
			if j, taken := owner[name]; taken {
				errs = append(errs, fmt.Errorf("mcp: %s is declared by both service #%d and service #%d; every name on a combined server must be unique", name, j, i))
				continue
			}
			owner[name] = i
		}
	}
	return errors.Join(errs...)
}

// inventory lists what reg declares, by asking a throwaway server over an
// in-memory session. The SDK keeps its registries private, so a session is the
// only way to read them back — and it reads them exactly as a client would.
func inventory(reg Registration) ([]string, error) {
	ctx := context.Background()
	probe := mcp.NewServer(&mcp.Implementation{Name: "inventory"}, nil)
	reg(probe)

	serverTransport, clientTransport := mcp.NewInMemoryTransports()
	ss, err := probe.Connect(ctx, serverTransport, nil)
	if err != nil {
		return nil, err
	}
	defer func() { _ = ss.Close() }()
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "inventory"}, nil).Connect(ctx, clientTransport, nil)
	if err != nil {
		return nil, err
	}
	defer func() { _ = cs.Close() }()

	// List only what the server advertises: asking for a kind it has none of
	// is an error, not an empty list.
	caps := cs.InitializeResult().Capabilities
	var names []string
	if caps.Tools != nil {
		for tool, err := range cs.Tools(ctx, nil) {
			if err != nil {
				return nil, err
			}
			names = append(names, fmt.Sprintf("tool %q", tool.Name))
		}
	}
	if caps.Prompts != nil {
		for prompt, err := range cs.Prompts(ctx, nil) {
			if err != nil {
				return nil, err
			}
			names = append(names, fmt.Sprintf("prompt %q", prompt.Name))
		}
	}
	if caps.Resources != nil {
		for resource, err := range cs.Resources(ctx, nil) {
			if err != nil {
				return nil, err
			}
			names = append(names, fmt.Sprintf("resource %q", resource.URI))
		}
		for template, err := range cs.ResourceTemplates(ctx, nil) {
			if err != nil {
				return nil, err
			}
			names = append(names, fmt.Sprintf("resource template %q", template.URITemplate))
		}
	}
	return names, nil
}
